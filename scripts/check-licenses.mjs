// npm run check:licenses
// Fails (exit 1) when something in the image engine has a licence that is not on the permissive list, or is unclear.
//  - models: every entry in scripts/models.manifest.json; blocked/unclear models must have no file on disk
//  - npm packages: every package installed under node_modules (declared licence)
//  - fonts: every bundled font folder must ship its OFL text
//  - docs: every model id must appear in LICENSES-MODELS.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.relative(root, p).replaceAll(String.fromCharCode(92), '/');

const ALLOWED = ['MIT', 'MIT-0', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'ISC', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense', 'Python-2.0', 'CC-BY-4.0', 'OFL-1.1', 'Zlib'];
const DISALLOWED = /\b(A?GPL|LGPL|SSPL|BUSL|Commons-Clause|CC-BY-NC|CC-BY-ND|CC-BY-SA|EUPL|MPL|OSL|RAIL|non-?commercial|research)/i;

// Packages that are not on the permissive list but are allowed on purpose. Each needs a reason and is printed on every run.
const EXCEPTIONS = {
  lightningcss: 'MPL-2.0, file-level copyleft. Pulled in by Vite as a build-time CSS tool. Nothing of it is shipped in the built app and we do not modify it.',
  'lightningcss-win32-x64-msvc': 'MPL-2.0, the Windows binary of lightningcss (same reason as above).',
};

const problems = [];
const notes = [];
const fail = (m) => problems.push(m);
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

/** True when an SPDX expression is acceptable: every OR branch needs only AND-parts that are allowed, and at least one branch passes. */
function spdxOk(expr) {
  const e = String(expr).replace(/[()]/g, ' ');
  if (DISALLOWED.test(e) && !/\bOR\b/.test(e)) return false;
  return e.split(/\s+OR\s+/i).some((branch) => branch.split(/\s+AND\s+/i).every((id) => ALLOWED.includes(id.trim())));
}

// ---- models
const manifest = readJson(path.join(root, 'scripts/models.manifest.json'));
const docs = fs.readFileSync(path.join(root, 'LICENSES-MODELS.md'), 'utf8');
const modelsDir = path.join(root, 'public/models');
const onDisk = fs.existsSync(modelsDir) ? fs.readdirSync(modelsDir).filter((f) => f.endsWith('.onnx')) : [];
const known = new Set();
for (const m of manifest.models) {
  known.add(m.file);
  if (m.upstream) known.add(m.upstream.file);
  if (!docs.includes(m.id)) fail(`model ${m.id}: not described in LICENSES-MODELS.md`);
  if (m.status === 'approved') {
    if (m.generate) notes.push(`model ${m.id}: generated by ${m.generate.script}, contains no third-party weights`);
    else {
      if (!spdxOk(m.licence)) fail(`model ${m.id}: licence "${m.licence}" is not on the permissive list (${ALLOWED.join(', ')})`);
      if (!m.licenceSources?.length) fail(`model ${m.id}: no licence source URLs recorded`);
      notes.push(`model ${m.id}: ${m.licence}`);
    }
  } else {
    if (m.status !== 'blocked') fail(`model ${m.id}: unknown status "${m.status}"`);
    if (!m.blockedBecause) fail(`model ${m.id}: blocked without a reason`);
    for (const f of [m.file, m.upstream?.file].filter(Boolean))
      if (fs.existsSync(path.join(modelsDir, f))) fail(`model ${m.id} is blocked (${m.licence}) but ${rel(path.join(modelsDir, f))} exists. Delete it.`);
    notes.push(`model ${m.id}: BLOCKED (${m.licence}), not downloaded`);
  }
}
for (const f of onDisk) if (!known.has(f)) fail(`public/models/${f} is not in the manifest, so its licence was never checked`);

// ---- npm packages
function* packages(dir) {
  if (!fs.existsSync(dir)) return;
  for (const name of fs.readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const p = path.join(dir, name);
    if (name.startsWith('@')) { yield* packages(p); continue; }
    const pj = path.join(p, 'package.json');
    if (fs.existsSync(pj)) yield pj;
    yield* packages(path.join(p, 'node_modules'));
  }
}
let count = 0;
const byLicence = {};
for (const pj of packages(path.join(root, 'node_modules'))) {
  const j = readJson(pj);
  count++;
  let lic = j.license ?? (Array.isArray(j.licenses) ? j.licenses.map((l) => l.type).join(' OR ') : j.licenses?.type);
  if (typeof lic === 'object') lic = lic?.type;
  const id = lic ?? 'NONE DECLARED';
  byLicence[id] = (byLicence[id] ?? 0) + 1;
  if (!lic) fail(`npm ${j.name}@${j.version}: no licence declared (${rel(pj)})`);
  else if (!spdxOk(lic) && EXCEPTIONS[j.name]) notes.push(`EXCEPTION ${j.name}@${j.version} (${lic}): ${EXCEPTIONS[j.name]}`);
  else if (!spdxOk(lic)) fail(`npm ${j.name}@${j.version}: "${lic}" is not on the permissive list`);
}
notes.push(`npm: ${count} packages checked, ${Object.entries(byLicence).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} x${v}`).join(', ')}`);

// ---- onnxruntime runtime files must match the manifest's package and version
const ortPkg = readJson(path.join(root, 'node_modules/onnxruntime-web/package.json'));
if (manifest.runtime?.version && ortPkg.version !== manifest.runtime.version) fail(`onnxruntime-web ${ortPkg.version} installed but the manifest pins ${manifest.runtime.version}`);

// ---- fonts
const fontsDir = path.join(root, 'src/image-engine/fonts');
for (const d of fs.readdirSync(fontsDir, { withFileTypes: true }).filter((e) => e.isDirectory())) {
  const files = fs.readdirSync(path.join(fontsDir, d.name));
  const ofl = files.find((f) => /^OFL/i.test(f));
  if (!ofl) fail(`font ${d.name}: no OFL.txt next to the font files`);
  else if (!/SIL OPEN FONT LICENSE/i.test(fs.readFileSync(path.join(fontsDir, d.name, ofl), 'utf8'))) fail(`font ${d.name}: ${ofl} is not the SIL Open Font License text`);
  notes.push(`font ${d.name}: ${ofl ? 'SIL OFL 1.1 text present' : 'MISSING licence'}`);
}

for (const n of notes) console.log('  ' + n);
if (problems.length) {
  console.error(`\nLICENCE CHECK FAILED (${problems.length}):`);
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}
console.log('\nLicence check passed.');
